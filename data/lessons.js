/* Lookup helpers */
MV.catalog = (function () {
  const modules = MV.data.modules;
  const byModule = Object.fromEntries(modules.map((m) => [m.id, m]));
  const flat = [];
  modules.forEach((m) => m.lessons.forEach((l, i) => flat.push({ ...l, module: m, moduleId: m.id, index: i, key: `${m.id}/${l.id}`, route: `#/lesson/${m.id}/${l.id}` })));
  const byKey = Object.fromEntries(flat.map((l) => [l.key, l]));
  return {
    modules,
    module: (id) => byModule[id],
    lessons: flat,
    lesson: (key) => byKey[key],
    next: (key) => { const i = flat.findIndex((l) => l.key === key); return i >= 0 ? flat[i + 1] : undefined; },
    prev: (key) => { const i = flat.findIndex((l) => l.key === key); return i > 0 ? flat[i - 1] : undefined; },
    contentPath: (moduleId) => `content/modules/${moduleId}.md`,
    totalMinutes: () => flat.reduce((s, l) => s + l.minutes, 0),
  };
})();
