#!/usr/bin/env node
/**
 * Builds assets/icons/icons.js — the subset of Lucide icons Microverse uses.
 *
 * Scans every JS file under js/ and data/ for string literals that are valid
 * Lucide icon names, then writes their SVG node data so the app needs no
 * 470 KB icon bundle at runtime. Also warns about icon('…') calls whose name
 * does not exist in Lucide (usually an icon that was renamed upstream).
 *
 * Usage: node tools/build-icons.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const LUCIDE_VERSION = '1.66.0';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

async function loadLucide() {
  const local = join(root, 'node_modules', 'lucide', 'dist', 'umd', 'lucide.min.js');
  let src;
  if (existsSync(local)) src = readFileSync(local, 'utf8');
  else {
    const url = `https://cdn.jsdelivr.net/npm/lucide@${LUCIDE_VERSION}/dist/umd/lucide.min.js`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Failed to download ${url}: ${res.status}`);
    src = await res.text();
  }
  const ctx = {};
  ctx.window = ctx; ctx.self = ctx; ctx.globalThis = ctx;
  vm.createContext(ctx);
  vm.runInContext(src, ctx);
  return ctx.lucide.icons;
}

const kebab = (pascal) => pascal.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (p.endsWith('.js')) out.push(p);
  }
  return out;
}

const icons = await loadLucide();
const byKebab = new Map();
for (const [name, node] of Object.entries(icons)) byKebab.set(kebab(name), node);

const files = [...walk(join(root, 'js')), ...walk(join(root, 'data'))];
const used = new Set();
const invalid = new Map();
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) if (byKebab.has(m[1])) used.add(m[1]);
  for (const m of src.matchAll(/icon\(\s*'([a-z0-9-]+)'/g)) if (!byKebab.has(m[1])) invalid.set(m[1], f.replace(root, '.'));
  for (const m of src.matchAll(/icon:\s*'([a-z0-9-]+)'/g)) if (!byKebab.has(m[1])) invalid.set(m[1], f.replace(root, '.'));
}

const data = {};
[...used].sort().forEach((n) => { data[n] = byKebab.get(n); });
const out = `/* Generated by tools/build-icons.mjs from Lucide v${LUCIDE_VERSION} (ISC licence). Do not edit by hand. */\nwindow.MV = window.MV || {};\nMV.iconData = ${JSON.stringify(data)};\n`;
writeFileSync(join(root, 'assets', 'icons', 'icons.js'), out);
console.log(`Wrote ${used.size} icons (${(out.length / 1024).toFixed(1)} KB) to assets/icons/icons.js`);
if (invalid.size) {
  console.warn('\nUnknown icon names (not in Lucide):');
  for (const [n, f] of invalid) console.warn(`  ${n}  (${f})`);
  process.exitCode = 1;
}
